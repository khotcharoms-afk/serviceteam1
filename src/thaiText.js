// src/thaiText.js — แก้ตัวอักษรแปลกปลอมที่ AI พิมพ์ปนในคำไทยเป็นครั้งคราว
// เช่น "เคسที่" (ตัว س อาหรับแทน ส ไทย) — โมเดลสุ่มตัวอักษรผิดชุดภาษา
// ตัวที่หน้าตา/เสียงคล้ายตัวไทยจะแทนด้วยตัวไทย ส่วนตัวอื่นจากชุดภาษาที่ระบบไม่ใช้
// (อาหรับ ฮีบรู ฮินดี ซีริลลิก จีน/ญี่ปุ่น/เกาหลี ฯลฯ) ที่อยู่ติดกับอักษรไทยจะถูกตัดทิ้ง

const LOOKALIKE = {
  "س": "ส", // س
  "ش": "ศ", // ش
  "ص": "ษ", // ص
  "ن": "น", // ن
  "م": "ม", // م
  "ر": "ร", // ر
  "ل": "ล", // ل
  "ك": "ก", // ك
  "ت": "ท", // ت
  "د": "ด", // د
  "ب": "บ", // ب
  "ا": "า", // ا
};

// ชุดภาษาที่ไม่ควรโผล่ในคำตอบภาษาไทย/อังกฤษของระบบ
const FOREIGN = "Ͱ-ϿЀ-ԯ֐-׿؀-ۿ܀-ࣿऀ-෿຀-໿ༀ-႟ᄀ-ᇿ぀-ヿ㐀-鿿가-힯";
const THAI = "฀-๿";
// ตัวแปลกปลอม 1 ตัวขึ้นไปที่มีอักษรไทยอยู่ข้างหน้าหรือข้างหลัง
const STRAY = new RegExp(`(?<=[${THAI}])[${FOREIGN}]+|[${FOREIGN}]+(?=[${THAI}])`, "g");

export function fixThaiText(text) {
  if (!text || typeof text !== "string") return text;
  return text.replace(STRAY, (run) => [...run].map((ch) => LOOKALIKE[ch] || "").join(""));
}
